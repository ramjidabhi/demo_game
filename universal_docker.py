def _detect_python_framework(entry_name: str, files, target_dir: Path = None):
    t_dir = target_dir or ROOT
    text = ""
    entry_path = (t_dir / entry_name) if entry_name else None
    if entry_path and entry_path.exists():
        text = _safe_read(entry_path)

    if re.search(r'^\s*(?:import\s+django|from\s+django\s+import)', text, re.M) or "DJANGO_SETTINGS_MODULE" in text:
        return "django"
    if re.search(r'^\s*(?:import\s+fastapi|from\s+fastapi\s+import)', text, re.M):
        return "fastapi"
    if re.search(r'^\s*(?:import\s+flask|from\s+flask\s+import)', text, re.M):
        return "flask"
    if re.search(r'^\s*(?:import\s+streamlit|from\s+streamlit\s+import)', text, re.M):
        return "streamlit"

    req_text = _safe_read(t_dir / "requirements.txt") + "\n" + _safe_read(t_dir / "pyproject.toml")
    if not req_text.strip():
        req_f = next((f for f in files if f.name == "requirements.txt"), None)
        pyproj_f = next((f for f in files if f.name == "pyproject.toml"), None)
        if req_f:
            req_text += _safe_read(req_f) + "\n"
        if pyproj_f:
            req_text += _safe_read(pyproj_f)

    if re.search(r'^(fastapi|uvicorn)\b', req_text, re.M | re.I):
        return "fastapi"
    if re.search(r'^(flask)\b', req_text, re.M | re.I):
        return "flask"
    if re.search(r'^(django)\b', req_text, re.M | re.I):
        return "django"
    if re.search(r'^(streamlit)\b', req_text, re.M | re.I):
        return "streamlit"

    for f in files:
        if f.suffix == ".py":
            f_txt = _safe_read(f)
            if re.search(r'^\s*(?:import\s+fastapi|from\s+fastapi\s+import)', f_txt, re.M):
                return "fastapi"
            if re.search(r'^\s*(?:import\s+flask|from\s+flask\s+import)', f_txt, re.M):
                return "flask"
            if re.search(r'^\s*(?:import\s+django|from\s+django\s+import)', f_txt, re.M):
                return "django"
            if re.search(r'^\s*(?:import\s+streamlit|from\s+streamlit\s+import)', f_txt, re.M):
                return "streamlit"

    if re.search(r'^\s*(?:from\s+http\.server\s+import|import\s+http\.server)', text, re.M):
        log("[i] Entry file uses Python standard library http.server.")
    return "generic"


def _detect_port(files, default: int) -> int:
    skip = {3306, 5432, 27017, 6379}
    env_files = [f for f in files if f.name.startswith(".env")]
    if ROOT.parent.exists() and ROOT.parent != ROOT:
        for pe in ROOT.parent.glob(".env*"):
            if pe.is_file() and pe not in env_files:
                env_files.append(pe)

    priority_files = env_files + [f for f in files if f.name in {
        "server.py", "app.py", "main.py", "server.js", "app.js",
        "server.ts", "app.ts", "main.ts", "index.ts",
        "Program.cs", "appsettings.json", "launchSettings.json",
        "application.properties", "application.yml"
    }]
    search_files = priority_files + [f for f in files if f not in priority_files and f.suffix in {".js", ".ts", ".py", ".cs", ".json", ".properties", ".toml", ".env"}]

    for f in search_files:
        text = _safe_read(f)
        m_env = re.search(r"^\s*PORT\s*=\s*(\d{2,5})\b", text, re.M)
        if m_env:
            v = int(m_env.group(1))
            if 1000 <= v < 65535 and v not in skip:
                return v

        m_def = re.search(r"PORT.*?\.default\((\d{2,5})\)", text, re.I | re.S)
        if m_def:
            v = int(m_def.group(1))
            if 1000 <= v < 65535 and v not in skip:
                return v

        for m in re.findall(
            r"(?:PORT\s*(?:[:=]|\|\|)\s*|\.listen\(\s*|server\.port\s*[:=]\s*|PORT\s*,\s*|ConfigureKestrel.*?ListenAnyIP\(\s*|\"applicationUrl\":\s*\"https?://[^:]+:)(\d{2,5})",
            text, re.I | re.S
        ):
            v = int(m)
            if 1000 <= v < 65535 and v not in skip:
                return v
    return default



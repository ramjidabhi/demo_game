def _fastapi_probe_snippet(entry=None):
    entry_candidate = ""
    if entry:
        e_mod = entry.replace("/", ".").replace("\\", ".")
        if e_mod.endswith(".py"):
            e_mod = e_mod[:-3]
        if e_mod:
            entry_candidate = f'"{e_mod}",'

    return f'''RUN cat > /app/_universal_start.py <<'PYEOF'
#!/usr/bin/env python3
import importlib, os, sys

def is_asgi(o):
    return o is not None and hasattr(o, "router") and hasattr(o, "routes") and callable(o)

candidates = []
env_mod = os.environ.get("UVICORN_MODULE")
if env_mod:
    candidates.append(env_mod.split(":")[0])
for m in ({entry_candidate}"server","main","app","api","asgi","application","src.main","app.main","server.main","src.app","src.server"):
    if m not in candidates:
        candidates.append(m)

found = None
for mn in candidates:
    try:
        mod = importlib.import_module(mn)
    except Exception:
        continue
    for name in ("app","application","asgi_app","api","server","main"):
        if is_asgi(getattr(mod, name, None)):
            found = f"{{mn}}:{{name}}"
            break
    if found:
        break
    for name in dir(mod):
        if not name.startswith("_") and is_asgi(getattr(mod, name, None)):
            found = f"{{mn}}:{{name}}"
            break
    if found:
        break

if not found:
    print("[_universal_start] No FastAPI/Starlette app found. Set UVICORN_MODULE=<mod>:<var>", file=sys.stderr)
    sys.exit(1)

os.execvp(sys.executable, [sys.executable, "-m", "uvicorn", found, "--host", os.environ.get("HOST", "0.0.0.0"), "--port", str(os.environ.get("PORT", "8000"))])
PYEOF
'''



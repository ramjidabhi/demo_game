def run_pipeline(clean=False, scan=False, meta=None):
    env = os.environ.copy()
    env.setdefault("COMPOSE_PROJECT_NAME", PROJECT_NAME)
    root_str = str(ROOT)

    try:
        subprocess.run(["docker", "compose", "version"], capture_output=True, check=True, env=env)
    except (FileNotFoundError, subprocess.CalledProcessError):
        error("Docker Compose is not available or Docker daemon is not running.")
        return False

    if clean:
        warn("Executing clean compose teardown with volume removal...")
        subprocess.run(["docker", "compose", "down", "-v", "--remove-orphans"], env=env, cwd=root_str)

    log("--- Checking Compose syntax ---", "34")
    r = subprocess.run(["docker", "compose", "config", "-q"], capture_output=True, text=True, encoding="utf-8", errors="replace", env=env, cwd=root_str)
    if r.returncode != 0:
        error(r.stderr.strip())
        return False

    log("--- Building & launching containers ---", "34")
    build_cmd = ["docker", "compose", "up", "-d", "--build"]
    res = subprocess.run(build_cmd, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace", cwd=root_str)
    if res.returncode != 0:
        err_output = (res.stderr or "") + "\n" + (res.stdout or "")
        print(err_output.strip())
        m_port_err = re.search(r"Bind for (?:0\.0\.0\.0|\[::\]|127\.0\.0\.1):(\d+) failed: port is already allocated", err_output, re.I)
        if m_port_err:
            collided_port = int(m_port_err.group(1))
            warn(f"Port {collided_port} is already allocated. Re-allocating to a free host port...")
            new_port = _find_free_host_port(collided_port + 1, exclude_project=PROJECT_NAME)
            env_path = ROOT / ".env"
            if env_path.exists():
                txt = env_path.read_text(encoding="utf-8")
                txt = re.sub(r"^HOST_PORT=.*$", f"HOST_PORT={new_port}", txt, flags=re.M)
                _write_file_lf(env_path, txt)
            env["HOST_PORT"] = str(new_port)
            log(f"[i] Retrying launch with HOST_PORT={new_port}...", "34")
            res_retry = subprocess.run(build_cmd, env=env, cwd=root_str)
            if res_retry.returncode != 0:
                error("Build/launch failed after port retry.")
                subprocess.run(["docker", "compose", "logs", "--tail=60"], env=env, cwd=root_str)
                return False
        else:
            error("Build/launch failed.")
            subprocess.run(["docker", "compose", "logs", "--tail=60"], env=env, cwd=root_str)
            return False

    log("--- Verifying health ---", "34")
    is_cli_or_build = meta and (meta.get("stack") == "android" or meta.get("dotnet_is_console"))
    is_monorepo = meta and meta.get("stack") == "fullstack_monorepo"

    for attempt in range(50):
        ps = subprocess.run(["docker", "compose", "ps", "--format", "json"],
                            capture_output=True, text=True, encoding="utf-8", errors="replace", env=env, cwd=root_str)
        try:
            raw = ps.stdout.strip()
            if raw.startswith("["):
                info = json.loads(raw)
            else:
                info = [json.loads(line) for line in raw.splitlines() if line.strip()]
        except Exception:
            info = []

        web_ok = False
        backend_ok = False
        frontend_ok = False
        all_ok = True
        for svc in info:
            name = svc.get("Service", "")
            state = svc.get("State", "")
            health = svc.get("Health", "")
            exit_code = svc.get("ExitCode", 0)

            if state == "exited":
                if is_cli_or_build and name == "web" and exit_code == 0:
                    web_ok = True
                    log(f"[i] Container '{name}' completed execution successfully (exit 0).", "36")
                    continue
                error(f"Container '{name}' exited unexpectedly with code {exit_code}!")
                subprocess.run(["docker", "compose", "logs", "--tail=60", name], env=env, cwd=root_str)
                return False
            if health == "unhealthy":
                error(f"Container '{name}' failed health checks (unhealthy).")
                subprocess.run(["docker", "compose", "logs", "--tail=60", name], env=env, cwd=root_str)
                return False

            if is_monorepo:
                if name == "backend":
                    if state == "running" and health in ("", "healthy"):
                        backend_ok = True
                    else:
                        all_ok = False
                elif name == "frontend":
                    if state == "running" and health in ("", "healthy"):
                        frontend_ok = True
                    else:
                        all_ok = False
                elif health not in ("", "healthy"):
                    all_ok = False
            else:
                if name == "web":
                    if state == "running" and health in ("", "healthy"):
                        web_ok = True
                    else:
                        all_ok = False
                elif health not in ("", "healthy"):
                    all_ok = False

        services_ready = (backend_ok and frontend_ok and all_ok) if is_monorepo else (web_ok and all_ok)

        if services_ready:
            log("[SUCCESS] All containers are running and healthy!", "32")
            subprocess.run(["docker", "compose", "ps"], env=env, cwd=root_str)
            host_port = "8080"
            backend_port = "5000"
            if (ROOT / ".env").exists():
                for line in (ROOT / ".env").read_text(encoding="utf-8").splitlines():
                    if line.startswith("HOST_PORT="):
                        host_port = line.split("=", 1)[1].strip()
                    elif line.startswith("BACKEND_PORT="):
                        backend_port = line.split("=", 1)[1].strip()
            print("=" * 60)
            if is_cli_or_build:
                print(f" [BUILD COMPLETE] Artifact generated successfully.")
            elif is_monorepo:
                print(f" [APP READY] Frontend: http://localhost:{host_port}")
                print(f" [APP READY] Backend : http://localhost:{backend_port}")
            else:
                print(f" [APP READY] Open in your browser: http://localhost:{host_port}")
            print("=" * 60)

            if scan:
                log("--- Running security vulnerability scan ---", "34")
                target_img = f"{PROJECT_NAME}_web:latest" if not is_monorepo else f"{PROJECT_NAME}_backend:latest"
                if shutil.which("trivy"):
                    scan_res = subprocess.run(["trivy", "image", "--severity", "HIGH,CRITICAL", target_img], cwd=root_str)
                    if scan_res.returncode != 0:
                        warn(f"Security scanner reported vulnerabilities for {target_img}.")
                elif shutil.which("docker"):
                    subprocess.run(["docker", "scout", "quickview", target_img], cwd=root_str)
            return True

        time.sleep(2)

    warn("Health check timed out waiting for all services to report healthy.")
    subprocess.run(["docker", "compose", "ps"], env=env, cwd=root_str)
    return False

    warn("Health check timed out waiting for all services to report healthy.")
    subprocess.run(["docker", "compose", "ps"], env=env, cwd=root_str)
    return False


def main():
    ap = argparse.ArgumentParser(description="Universal Project-to-Container Engine (v15)")
    ap.add_argument("--path", "-C", type=str, default=".", help="Target project directory (default: current directory)")
    ap.add_argument("--force", action="store_true", help="Overwrite generated files")
    ap.add_argument("--dry-run", action="store_true", help="Scan and show detected config without building")
    ap.add_argument("--no-run", "--generate-only", action="store_true", help="Generate Docker files without starting containers")
    ap.add_argument("--clean", action="store_true", help="Run 'docker compose down -v' before building")
    ap.add_argument("--no-db", action="store_true", help="Do not spin up database containers")
    ap.add_argument("--databases", type=str, default=None, help="Comma-separated databases (postgres,mariadb,mongodb,redis)")
    ap.add_argument("--port", type=int, default=None, help="Explicit port override")
    ap.add_argument("--start-period", type=int, default=None, help="Health check start grace period in seconds")
    ap.add_argument("--scan", action="store_true", help="Run container vulnerability scan after build")
    args = ap.parse_args()

    global ROOT, RAW_NAME, PROJECT_NAME
    if args.path and args.path != ".":
        ROOT = Path(args.path).resolve()
        RAW_NAME = ROOT.name.lower()
        PROJECT_NAME = _sanitize_project_name(RAW_NAME)

    meta = inspect_project(db_override=args.databases, no_db=args.no_db)
    if args.port:
        meta["port"] = args.port

    _adapt_php_database_configs(meta)
    _adapt_node_source_bugs(meta)

    print("=" * 60)
    print(f"[*] Project Name : {PROJECT_NAME}")
    print(f"[*] Stack        : {meta['stack'].upper()}")
    if meta["stack"] == "dotnet":
        legacy_lbl = " [Windows .NET Framework / Mono]" if meta.get("dotnet_is_legacy") else ""
        console_lbl = " [Console App]" if meta.get("dotnet_is_console") else ""
        print(f"[*] Runtime      : .NET {meta['dotnet_version']} ({meta['dotnet_dll']}){legacy_lbl}{console_lbl}")
    elif meta["stack"] == "java":
        spring_lbl = " [Spring Boot]" if meta.get("is_spring") else ""
        print(f"[*] Runtime      : Java {meta['java_version']} ({meta['java_tool']}){spring_lbl}")
    elif meta["stack"] == "android":
        print(f"[*] Runtime      : Android Mobile Application (Gradle SDK Build)")
    elif meta["stack"] == "go":
        cgo_lbl = " [CGO Enabled]" if meta.get("go_cgo") else ""
        print(f"[*] Runtime      : Go {meta['go_version']}{cgo_lbl}")
    elif meta["stack"] == "python":
        tools_lbl = " [build-essential enabled]" if meta.get("python_needs_build_tools") else ""
        print(f"[*] Framework    : {meta['framework'].upper()} (Python {meta['python_version']} / {meta['python_backend']}){tools_lbl}")
    elif meta["stack"] == "node":
        lock_lbl = f" via {meta['lockfile']}" if meta.get("lockfile") else ""
        print(f"[*] Framework    : {meta['framework'].upper()} (Node {meta['node_version']} / {meta['pkg_manager']}{lock_lbl})")
    elif meta["stack"] == "fullstack_monorepo":
        b_meta = meta.get("backend_meta", {})
        f_meta = meta.get("frontend_meta", {})
        print(f"[*] Backend      : {b_meta.get('stack', '').upper()} / {b_meta.get('framework', '').upper()} (Entry: {b_meta.get('entry')}, Port: {b_meta.get('port')})")
        print(f"[*] Frontend     : {f_meta.get('stack', '').upper()} (Port: {f_meta.get('port')})")

    print(f"[*] Port         : {meta['port']}")
    print(f"[*] Entrypoint   : {meta['entry']}")
    print(f"[*] Databases    : {', '.join(d.upper() for d in meta['databases']) if meta['databases'] else 'NONE (Self-contained)'}")
    if meta.get("db_name"):
        print(f"[*] DB Name      : {meta['db_name']}")
    if meta.get("db_init_sql"):
        print(f"[*] DB Init SQL  : {meta['db_init_sql']}")
    if meta.get("sqlite_file"):
        print(f"[*] SQLite DB    : {meta['sqlite_file']}")
    print("=" * 60)

    if args.dry_run:
        return 0

    generate_dockerfile(meta, args.force)
    if meta["stack"] in {"spa", "static"} and not meta.get("target_subdir") and meta["stack"] != "fullstack_monorepo":
        generate_nginx_conf(meta, args.force)
    generate_dockerignore(meta=meta, force=args.force)
    generate_compose(meta, args.force, start_period_override=args.start_period)

    if args.no_run:
        log("[SUCCESS] Docker configuration generated successfully (--no-run).", "32")
        return 0

    return 0 if run_pipeline(clean=args.clean, scan=args.scan, meta=meta) else 1


if __name__ == "__main__":
    sys.exit(main())

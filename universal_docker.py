def _write_env(meta, force=False):
    env_path = ROOT / ".env"
    example_path = ROOT / ".env.example"
    existing = {}

    if env_path.exists():
        for line in env_path.read_text(encoding="utf-8", errors="ignore").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                existing[k.strip()] = v.strip()

    required = {
        "postgres": ["POSTGRES_PASSWORD"],
        "mariadb": ["MARIADB_ROOT_PASSWORD", "MARIADB_PASSWORD"],
        "mongodb": ["MONGODB_PASSWORD"],
        "redis": ["REDIS_PASSWORD"],
    }

    needed = set()
    for db in meta["databases"]:
        needed.update(required.get(db, []))

    changed = False
    docker_occupied = _get_docker_occupied_ports(exclude_project=PROJECT_NAME)
    current_host_port = existing.get("HOST_PORT")

    need_port_alloc = False
    if meta.get("port") is not None:
        if current_host_port is None or force:
            need_port_alloc = True
        else:
            try:
                hp = int(current_host_port)
                if _is_port_occupied(hp, docker_occupied):
                    warn(f"Configured HOST_PORT={hp} is currently occupied by another container or process.")
                    need_port_alloc = True
            except ValueError:
                need_port_alloc = True
    else:
        if "HOST_PORT" in existing:
            del existing["HOST_PORT"]
            changed = True

    if need_port_alloc and meta.get("port") is not None:
        target = meta.get("port", 8080)
        assigned_port = _find_free_host_port(target, exclude_project=PROJECT_NAME)
        existing["HOST_PORT"] = str(assigned_port)
        docker_occupied.add(assigned_port)
        changed = True
        log(f"[i] Host port dynamically allocated: {assigned_port}", "36")

    # For fullstack monorepos: allocate BACKEND_PORT
    if meta.get("stack") == "fullstack_monorepo" and meta.get("backend_port") is not None:
        current_backend_port = existing.get("BACKEND_PORT")
        need_backend_alloc = False
        if current_backend_port is None or force:
            need_backend_alloc = True
        else:
            try:
                bp = int(current_backend_port)
                if _is_port_occupied(bp, docker_occupied):
                    warn(f"Configured BACKEND_PORT={bp} is currently occupied by another container or process.")
                    need_backend_alloc = True
            except ValueError:
                need_backend_alloc = True
        if need_backend_alloc:
            b_target = meta.get("backend_port", 5000)
            assigned_bp = _find_free_host_port(b_target, exclude_project=PROJECT_NAME)
            existing["BACKEND_PORT"] = str(assigned_bp)
            docker_occupied.add(assigned_bp)
            changed = True
            log(f"[i] Backend host port dynamically allocated: {assigned_bp}", "36")

    # Important: Preserve existing database credentials even on --force to prevent breaking active volumes
    for var in needed:
        if not existing.get(var):
            existing[var] = secrets.token_hex(16)
            changed = True

    if changed or not env_path.exists():
        header = f"# {PROJECT_NAME} — generated {time.strftime('%Y-%m-%d')} (Dev only: do not commit)"
        lines = [header] + [f"{k}={v}" for k, v in existing.items()]
        _write_file_lf(env_path, "\n".join(lines) + "\n")
        if hasattr(os, "chmod"):
            try:
                os.chmod(env_path, 0o600)
            except Exception:
                pass
        hp_lbl = f"HOST_PORT={existing['HOST_PORT']}" if 'HOST_PORT' in existing else "CLI/Self-contained"
        bp_lbl = f", BACKEND_PORT={existing['BACKEND_PORT']}" if 'BACKEND_PORT' in existing else ""
        log(f"[OK] .env written / updated ({hp_lbl}{bp_lbl}).")

    if not example_path.exists():
        meta_p = meta.get('port') or ''
        lines = [f"# {PROJECT_NAME} — copy to .env", f"HOST_PORT={meta_p}"]
        if meta.get("stack") == "fullstack_monorepo":
            lines.append(f"BACKEND_PORT={meta.get('backend_port', 5000)}")
        for var in required:
            if var not in {"HOST_PORT", "BACKEND_PORT"}:
                lines.append(f"{var}=")
        _write_file_lf(example_path, "\n".join(lines) + "\n")
        log("[OK] .env.example written.")



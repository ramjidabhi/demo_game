def _detect_databases_accurately(files, names):
    dbs = set()
    raw_db_name = None
    db_init_sql = None
    sqlite_file = None

    req_text = ""
    pkg_text = ""
    pom_text = ""
    go_text = ""
    cargo_text = ""
    gem_text = ""
    composer_text = ""
    env_text = ""

    for f in files:
        if f.name in {"requirements.txt", "pyproject.toml", "Pipfile"}:
            req_text += _safe_read(f) + "\n"
        elif f.name == "package.json":
            pkg_text += _safe_read(f) + "\n"
        elif f.name in {"pom.xml", "build.gradle", "build.gradle.kts"}:
            pom_text += _safe_read(f) + "\n"
        elif f.name == "go.mod":
            go_text += _safe_read(f) + "\n"
        elif f.name == "Cargo.toml":
            cargo_text += _safe_read(f) + "\n"
        elif f.name == "Gemfile":
            gem_text += _safe_read(f) + "\n"
        elif f.name == "composer.json":
            composer_text += _safe_read(f) + "\n"
        elif f.name.startswith(".env"):
            env_text += _safe_read(f) + "\n"

    if ROOT.parent.exists() and ROOT.parent != ROOT:
        for pe in ROOT.parent.glob(".env*"):
            if pe.is_file():
                env_text += _safe_read(pe) + "\n"

    dotnet_manifests = ""
    for f in files:
        if f.suffix in {".csproj", ".fsproj"}:
            dotnet_manifests += _safe_read(f) + "\n"
        elif f.name.startswith("appsettings") and f.suffix == ".json":
            text = _safe_read(f)
            dotnet_manifests += text + "\n"
            m_db = re.search(r"database=([a-zA-Z0-9_-]+)", text, re.I)
            if m_db and not raw_db_name:
                raw_db_name = m_db.group(1)

    # Check env variables for database URLs and names
    if env_text:
        m_pg = re.search(r"(?:DATABASE_URL|POSTGRES_URL)\s*=\s*['\"]?postgres(?:ql)?://[^/]+/([a-zA-Z0-9_-]+)", env_text, re.I)
        if m_pg:
            dbs.add("postgres")
            if not raw_db_name:
                raw_db_name = m_pg.group(1)
        m_my = re.search(r"(?:DATABASE_URL|MYSQL_URL)\s*=\s*['\"]?mysql://[^/]+/([a-zA-Z0-9_-]+)", env_text, re.I)
        if m_my:
            dbs.add("mariadb")
            if not raw_db_name:
                raw_db_name = m_my.group(1)
        m_mg = re.search(r"(?:MONGODB_URI|MONGO_URI)\s*=\s*['\"]?mongodb(?:\+srv)?://[^/]+/([a-zA-Z0-9_-]+)", env_text, re.I)
        if m_mg:
            dbs.add("mongodb")
            if not raw_db_name:
                raw_db_name = m_mg.group(1)
        if not raw_db_name:
            m_named = re.search(r"^\s*(?:POSTGRES_DB|MYSQL_DATABASE|MARIADB_DATABASE|DB_NAME)\s*=\s*['\"]?([a-zA-Z0-9_-]+)", env_text, re.M | re.I)
            if m_named:
                raw_db_name = m_named.group(1)

    manifests = f"{req_text}\n{pkg_text}\n{pom_text}\n{go_text}\n{cargo_text}\n{gem_text}\n{composer_text}\n{dotnet_manifests}"

    # PostgreSQL
    if re.search(r"(psycopg2|psycopg|asyncpg|npgsql|postgresql|jdbc:postgresql|pg_dump|\"pg\"|\"postgres\"|tokio-postgres|jackc/pgx|lib/pq)", manifests, re.I):
        dbs.add("postgres")

    # MySQL / MariaDB
    if re.search(r"(mysqlclient|pymysql|mariadb|mysql2|jdbc:mysql|go-sql-driver/mysql|pomelo|mysqlconnector|mysql\.data|port=3306)", manifests, re.I):
        dbs.add("mariadb")

    # MongoDB
    if re.search(r"(pymongo|motor|mongoose|mongodb\.driver|mongo-driver|spring-boot-starter-data-mongodb)", manifests, re.I):
        dbs.add("mongodb")

    # Redis
    if re.search(r"(redis|ioredis|go-redis|spring-boot-starter-data-redis|predis|stackexchange\.redis)", manifests, re.I):
        dbs.add("redis")

    # SQLite
    for f in files:
        if f.suffix in {".db", ".sqlite", ".sqlite3"}:
            dbs.add("sqlite")
            try:
                sqlite_file = f.relative_to(ROOT).as_posix()
            except Exception:
                sqlite_file = f.name
            break

    if not sqlite_file and (re.search(r"(import\s+sqlite3|sqlite3|better-sqlite3|microsoft\.entityframeworkcore\.sqlite)", manifests)):
        dbs.add("sqlite")

    # SQL Schema detection: ANY .sql file in project
    sql_files = [f for f in files if f.suffix == ".sql"]
    if sql_files:
        def sql_priority(f):
            stem = f.stem.lower()
            if stem in {"schema", "init", "database", "db"}:
                return (0, -f.stat().st_size)
            if PROJECT_NAME in stem or any(p in stem for p in PROJECT_NAME.split("_") if len(p) > 2):
                return (1, -f.stat().st_size)
            if f.parent == ROOT:
                return (2, -f.stat().st_size)
            return (3, -f.stat().st_size)

        sorted_sql = sorted(sql_files, key=sql_priority)
        best_sql = sorted_sql[0]
        db_init_sql = best_sql.relative_to(ROOT).as_posix()

        # SQL content dialect & schema analysis
        pg_signals = 0
        mysql_signals = 0
        pg_pattern = re.compile(r"\b(?:pgcrypto|uuid_generate_v4|gen_random_uuid|timestamptz|bigserial|smallserial|serial|bytea|plpgsql|citext|inet|cidr|macaddr|jsonb)\b|CREATE\s+EXTENSION|CREATE\s+TYPE\s+[a-zA-Z0-9_]+\s+AS\s+ENUM", re.I)
        mysql_pattern = re.compile(r"\b(?:engine\s*=\s*(?:innodb|myisam|memory|aria)|auto_increment|utf8mb4_|latin1_swedish_ci)\b|LOCK\s+TABLES", re.I)

        for f in sorted_sql:
            sql_text = _safe_read(f)
            if pg_pattern.search(sql_text):
                pg_signals += 1
            if mysql_pattern.search(sql_text):
                mysql_signals += 1

            m_db = re.search(r"CREATE\s+DATABASE(?:\s+IF\s+NOT\s+EXISTS)?\s+[`\"']?([a-zA-Z0-9_-]+)[`\"']?", sql_text, re.I)
            if not m_db:
                m_db = re.search(r"USE\s+[`\"']?([a-zA-Z0-9_-]+)[`\"']?", sql_text, re.I)
            if not m_db:
                m_db = re.search(r"Database:\s*[`\"']?([a-zA-Z0-9_-]+)[`\"']?", sql_text, re.I)
            if m_db and not raw_db_name:
                raw_db_name = m_db.group(1)

            # Ignore generic migration numbers like 001_init, 01_schema, etc.
            is_generic = bool(re.match(r"^(?:v?\d+[_\-]*)*(?:init|schema|migration|setup|create|tables?|db|database|data|dump|backup)\b", f.stem.lower()))
            if not raw_db_name and not is_generic:
                raw_db_name = f.stem

        if "mariadb" not in dbs and "postgres" not in dbs:
            if pg_signals > mysql_signals:
                dbs.add("postgres")
            else:
                dbs.add("mariadb")

    # PHP database connection scanning
    for f in files:
        if f.suffix == ".php" or f.name in {"config.php", "database.php", "db.php", "conn.php", "connection.php"}:
            php_text = _safe_read(f)
            if re.search(r"(pdo_mysql|mysql:|mysqli|mysqli_connect|mysql_connect)", php_text, re.I):
                dbs.add("mariadb")
            if not raw_db_name:
                m_db = re.search(r"dbname\s*=\s*['\"]([^'\"]+)['\"]", php_text, re.I)
                if not m_db:
                    m_db = re.search(r"new\s+mysqli\s*\(\s*[^,]+,\s*[^,]+,\s*[^,]+,\s*['\"]([a-zA-Z0-9_-]+)['\"]", php_text, re.I)
                if not m_db:
                    m_db = re.search(r"mysqli_connect\s*\(\s*[^,]+,\s*[^,]+,\s*[^,]+,\s*['\"]([a-zA-Z0-9_-]+)['\"]", php_text, re.I)
                if not m_db:
                    m_db = re.search(r"mysql_select_db\s*\(\s*['\"]([a-zA-Z0-9_-]+)['\"]", php_text, re.I)
                if not m_db:
                    m_db = re.search(r"define\s*\(\s*['\"]DB_NAME['\"]\s*,\s*['\"]([a-zA-Z0-9_-]+)['\"]", php_text, re.I)
                if m_db:
                    raw_db_name = m_db.group(1)

    # Python database connection scanning
    for f in files:
        if f.suffix == ".py" and not raw_db_name:
            py_text = _safe_read(f)
            m_db = re.search(r"['\"]NAME['\"]\s*:\s*['\"]([a-zA-Z0-9_-]+)['\"]", py_text)
            if not m_db:
                m_db = re.search(r"create_engine\s*\(['\"][^'\"]*\/([a-zA-Z0-9_-]+)['\"]", py_text)
            if m_db:
                raw_db_name = m_db.group(1)

    # Node.js database connection scanning
    for f in files:
        if f.suffix in {".js", ".ts"} and not raw_db_name:
            js_text = _safe_read(f)
            m_db = re.search(r"database\s*:\s*['\"]([a-zA-Z0-9_-]+)['\"]", js_text)
            if m_db:
                raw_db_name = m_db.group(1)

    final_db_name = _sanitize_db_name(raw_db_name if raw_db_name else PROJECT_NAME)
    return sorted(dbs), final_db_name, db_init_sql, sqlite_file


def _adapt_php_database_configs(meta):
    """
    Ensures PHP database connection files use environment variables
    for Docker container networking while retaining local fallback.
    Preserves original files with a .bak extension.
    """
    if meta.get("stack") != "php" or "mariadb" not in meta.get("databases", []):
        return

    db_name = meta.get("db_name", "app_db")
    candidate_names = {"db.php", "config.php", "database.php", "conn.php", "connection.php"}

    files = [p for p in ROOT.rglob("*.php") if not any(part in SKIP_DIRS for part in p.parts)]
    for f in files:
        is_candidate = f.name.lower() in candidate_names or any(part.lower() in {"includes", "inc", "config"} for part in f.parts)
        if not is_candidate:
            continue

        content = _safe_read(f)
        if "getenv('DB_HOST')" in content or 'getenv("DB_HOST")' in content:
            continue

        # Look for hardcoded mysqli: $conn = new mysqli("localhost", ...)
        m_mysqli = re.search(r'(?:\$(\w+)\s*=\s*)?new\s+mysqli\s*\(\s*["\']localhost["\']\s*,\s*["\']([^"\']*)["\']\s*,\s*["\']([^"\']*)["\']\s*,\s*["\']([^"\']*)["\']\s*\)', content)
        if m_mysqli:
            var_name = m_mysqli.group(1) or "conn"
            orig_user = m_mysqli.group(2) or "root"
            orig_pass = m_mysqli.group(3) or ""
            orig_db = m_mysqli.group(4) or db_name

            backup_file = f.with_suffix(f.suffix + ".bak")
            if not backup_file.exists():
                shutil.copyfile(f, backup_file)

            replacement = (
                f"$db_host = getenv('DB_HOST') ?: (getenv('MYSQL_HOST') ?: 'localhost');\n"
                f"$db_user = getenv('DB_USER') ?: (getenv('MYSQL_USER') ?: '{orig_user}');\n"
                f"$db_pass = getenv('DB_PASSWORD') !== false ? getenv('DB_PASSWORD') : (getenv('MYSQL_PASSWORD') !== false ? getenv('MYSQL_PASSWORD') : '{orig_pass}');\n"
                f"$db_name = getenv('DB_NAME') ?: (getenv('MYSQL_DATABASE') ?: '{orig_db}');\n"
                f"$db_port = (int)(getenv('DB_PORT') ?: (getenv('MYSQL_PORT') ?: 3306));\n"
                f"${var_name} = new mysqli($db_host, $db_user, $db_pass, $db_name, $db_port)"
            )
            new_content = content[:m_mysqli.start()] + replacement + content[m_mysqli.end():]
            _write_file_lf(f, new_content)
            log(f"[OK] Adapted {f.relative_to(ROOT)} for Docker database connectivity (backup: {f.name}.bak).")


def _adapt_node_source_bugs(meta):
    """
    Detects and resiliently adapts common Node.js runtime code bugs,
    such as missing middleware imports (e.g. undefined logger),
    preserving original files with .bak extension.
    """
    if meta.get("stack") not in {"node", "fullstack_monorepo"}:
        return

    for f in ROOT.rglob("*.js"):
        if any(part in SKIP_DIRS for part in f.parts):
            continue
        txt = _safe_read(f)
        if re.search(r"app\.use\s*\(\s*logger\s*\(", txt) and not re.search(r"\b(?:const|let|var|function)\s+logger\b", txt):
            backup = f.with_suffix(f.suffix + ".bak")
            if not backup.exists():
                shutil.copyfile(f, backup)
            patched = "const logger = (format) => (req, res, next) => next();\n" + txt
            _write_file_lf(f, patched)
            log(f"[OK] Resiliently patched undefined logger in {f.relative_to(ROOT)} (backup: {f.name}.bak).")



def log(msg: str, color: str = "32"):
    print(f"\033[{color}m{msg}\033[0m")


def warn(msg: str):
    print(f"\033[33m[!] {msg}\033[0m")


def error(msg: str):
    print(f"\033[31m[ERROR] {msg}\033[0m")


def _is_generated(p: Path) -> bool:
    if not p.exists():
        return False
    try:
        content = p.read_text(encoding="utf-8", errors="ignore")
        return GENERATED_MARKER in content
    except Exception:
        return False


def _with_marker(content: str) -> str:
    content = content.lstrip()
    if content.startswith(GENERATED_MARKER):
        return content
    return f"{GENERATED_MARKER}\n{content}"


def _write_file_lf(path: Path, content: str):
    # Normalize line endings and strip invisible non-breaking spaces (U+00A0)
    content = content.replace("\u00a0", " ").replace("\r\n", "\n").replace("\r", "\n")
    path.write_text(content, encoding="utf-8", newline="\n")


def _safe_read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return ""


def _sanitize_db_name(name: str) -> str:
    clean = re.sub(r"[^a-z0-9_]", "_", name.lower()).strip("_")
    reserved = {"select", "table", "database", "user", "order", "group", "admin", "system"}
    if not clean or clean in reserved:
        return f"{clean}_db" if clean else "app_db"
    return clean[:63]


def _get_docker_occupied_ports(exclude_project: str = None) -> set:
    """Query Docker daemon to discover all host ports mapped by other containers."""
    occupied = set()
    try:
        r = subprocess.run(
            ["docker", "ps", "-a", "--format", "{{.Names}}\t{{.Ports}}"],
            capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=5
        )
        if r.returncode == 0:
            for line in r.stdout.strip().splitlines():
                if "\t" in line:
                    c_name, p_info = line.split("\t", 1)
                    if exclude_project and (c_name.startswith(exclude_project) or f"_{exclude_project}_" in c_name):
                        continue
                    for m in re.findall(r":(\d+)->", p_info):
                        try:
                            occupied.add(int(m))
                        except ValueError:
                            pass
    except Exception:
        pass
    return occupied


def _is_port_occupied(port: int, docker_occupied: set = None) -> bool:
    """Checks if a port is in use by Docker container port mappings or on the host."""
    if docker_occupied and port in docker_occupied:
        return True
    for host in ("127.0.0.1", "localhost"):
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
                s.settimeout(0.3)
                if s.connect_ex((host, port)) == 0:
                    return True
        except Exception:
            pass
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            s.bind(("0.0.0.0", port))
    except Exception:
        return True
    return False


def _find_free_host_port(target_port: int, exclude_project: str = None) -> int:
    """Finds a guaranteed free port on the host, starting from target_port."""
    if target_port is None:
        target_port = 8080
    docker_occupied = _get_docker_occupied_ports(exclude_project)
    if target_port == 80:
        candidates = [80, 8080, 8081, 8082, 8083, 8084, 8085, 8088, 8090, 8000, 8001, 8888]
        candidates.extend(range(8080, 8200))
    else:
        candidates = [target_port] + list(range(target_port + 1, target_port + 100))

    for p in candidates:
        if p == 80 and _is_port_occupied(80, docker_occupied):
            continue
        if not _is_port_occupied(p, docker_occupied):
            return p

    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("", 0))
        return s.getsockname()[1]



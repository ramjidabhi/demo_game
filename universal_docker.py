def _sanitize_requirements_file(target_dir: Path = None):
    t_dir = target_dir or ROOT
    req_path = t_dir / "requirements.txt"
    if not req_path.exists():
        return False
    text = _safe_read(req_path)
    os_skip = {"pywin32", "pypiwin32", "windows-curses"}
    out = []
    for line in text.splitlines():
        trimmed = line.strip()
        if not trimmed or trimmed.startswith("#"):
            out.append(trimmed)
            continue
        pkg = re.split(r"[=<>!~]", trimmed)[0].strip()
        if pkg.lower() in os_skip:
            continue
        # Fix yanked mysql-connector-python versions: 8.0.6 to 8.0.22 (Oracle deleted these from PyPI)
        if re.match(r"^mysql-connector-python==8\.0\.(?:[6-9]|1[0-9]|2[0-2])\b", trimmed, re.I):
            trimmed = "mysql-connector-python>=8.0.23"
        out.append(trimmed)

    clean_path = t_dir / "requirements.docker.txt"
    _write_file_lf(clean_path, "\n".join(out) + "\n")
    return True



def _inspect_single_project(target_dir: Path, db_override: str = None, no_db: bool = False) -> dict:
    files = []
    for p in target_dir.rglob("*"):
        if any(part in SKIP_DIRS for part in p.parts):
            continue
        if p.is_file():
            if p.name in SKIP_FILES or p.name.endswith(".bak") or p.suffix in {".tmp", ".log"}:
                continue
            files.append(p)

    names = {f.name for f in files}
    rel = {f.relative_to(target_dir).as_posix() for f in files}
    root_files = [f for f in files if f.parent == target_dir]
    root_names = {f.name for f in root_files}
    meta = _blank_meta()
    meta["target_dir"] = target_dir

    # 1. Android Application
    if ("AndroidManifest.xml" in names
          or any("com.android.application" in _safe_read(f) or "com.android.library" in _safe_read(f)
                 for f in files if f.name in {"build.gradle", "build.gradle.kts"})):
        meta.update(stack="android", port=None, entry="gradlew")

    # 2. .NET / C#
    elif any(f.suffix in {".csproj", ".sln", ".fsproj"} for f in files if f.parent in {target_dir, target_dir / target_dir.name} or f.name in root_names):
        meta.update(stack="dotnet", port=_detect_port(files, 8080), entry="Program.cs")
        dotnet_ver = "9.0"
        dll_name = None
        is_legacy = False
        is_console = False

        csproj_files = [f for f in files if f.suffix == ".csproj"]
        target_csproj = csproj_files[0] if csproj_files else None
        for cf in csproj_files:
            c_text = _safe_read(cf)
            if "Microsoft.NET.Sdk.Web" in c_text:
                target_csproj = cf
                break

        if target_csproj:
            c_text = _safe_read(target_csproj)
            m_tf = re.search(r"<TargetFramework>net(\d+(?:\.\d+)?)</TargetFramework>", c_text, re.I)
            if m_tf:
                raw_ver = m_tf.group(1)
                dotnet_ver = raw_ver if "." in raw_ver else f"{raw_ver}.0"
            else:
                m_legacy = re.search(r"<TargetFrameworkVersion>v?([0-9.]+)</TargetFrameworkVersion>", c_text, re.I)
                if m_legacy:
                    is_legacy = True
                    dotnet_ver = f"v{m_legacy.group(1)}"

            if "<OutputType>Exe</OutputType>" in c_text and "Microsoft.NET.Sdk.Web" not in c_text:
                is_console = True

            m_asm = re.search(r"<AssemblyName>([^<]+)</AssemblyName>", c_text, re.I)
            if m_asm:
                dll_name = f"{m_asm.group(1).strip()}.dll"
            else:
                dll_name = f"{target_csproj.stem}.dll"

        meta["dotnet_version"] = dotnet_ver
        meta["dotnet_dll"] = dll_name or f"{PROJECT_NAME}.dll"
        meta["dotnet_is_legacy"] = is_legacy
        meta["dotnet_is_console"] = is_console
        if is_console:
            meta["port"] = None

    # 3. Node.js / JavaScript / TypeScript / SPA
    elif "package.json" in root_names or ("package.json" in names and len(files) < 40):
        pkg_path = target_dir / "package.json"
        try:
            pkg = json.loads(pkg_path.read_text(encoding="utf-8", errors="ignore"))
        except Exception:
            pkg = {}
        scripts = pkg.get("scripts", {})
        meta["has_build"] = "build" in scripts

        # Lockfile & Package manager detection
        if "pnpm-lock.yaml" in names:
            meta["pkg_manager"] = "pnpm"
            meta["lockfile"] = "pnpm-lock.yaml"
        elif "yarn.lock" in names:
            meta["pkg_manager"] = "yarn"
            meta["lockfile"] = "yarn.lock"
        elif "bun.lock" in names or "bun.lockb" in names:
            meta["pkg_manager"] = "bun"
            meta["lockfile"] = "bun.lock" if "bun.lock" in names else "bun.lockb"
        elif "package-lock.json" in names:
            meta["pkg_manager"] = "npm"
            meta["lockfile"] = "package-lock.json"
        else:
            meta["pkg_manager"] = "npm"
            meta["lockfile"] = None

        meta["node_version"] = _detect_node_version(files, pkg)

        start_script = scripts.get("start", "")
        meta["node_needs_dev_runtime"] = any(tool in start_script for tool in ["ts-node", "tsx", "nodemon", "babel-node"])

        spa_configs = {"vite.config.js", "vite.config.ts", "angular.json", "vue.config.js", "svelte.config.js"}
        nxt_configs = {"next.config.js", "next.config.mjs", "next.config.ts"}
        if any(m in names for m in spa_configs):
            meta["stack"] = "spa"
            meta["port"] = 80
        elif any(m in names for m in nxt_configs):
            meta["stack"] = "node"
            meta["framework"] = "nextjs"
            meta["port"] = _detect_port(files, 3000)
            for nxt_f in files:
                if nxt_f.name in nxt_configs:
                    nxt_txt = _safe_read(nxt_f)
                    clean_nxt = re.sub(r"//.*$", "", nxt_txt, flags=re.M)
                    clean_nxt = re.sub(r"/\*.*?\*/", "", clean_nxt, flags=re.S)
                    if re.search(r"output\s*:\s*['\"]standalone['\"]", clean_nxt):
                        meta["next_standalone"] = True
                        break
        else:
            meta["stack"] = "node"
            meta["port"] = _detect_port(files, 3000)

        if "start" in scripts:
            meta["entry"] = "start"
        elif "main" in pkg and (target_dir / pkg["main"]).exists():
            meta["entry"] = pkg["main"]
        else:
            for c in ["server.js", "app.js", "index.js", "src/server.js", "src/index.js",
                      "server.ts", "src/server.ts", "src/index.ts"]:
                if c in rel:
                    meta["entry"] = c
                    break
        if not meta["entry"]:
            meta["entry"] = "index.js"

    # 4. Python
    elif (any(x in root_names for x in ["requirements.txt", "pyproject.toml", "Pipfile", "setup.py", "manage.py", "app.py", "main.py"])
          or any(f.suffix == ".py" for f in files)):
        meta["stack"] = "python"
        meta["port"] = _detect_port(files, 8000)
        meta["python_version"] = _detect_python_version(files, target_dir)

        if "poetry.lock" in names or ("pyproject.toml" in names and "[tool.poetry]" in _safe_read(target_dir / "pyproject.toml")):
            meta["python_backend"] = "poetry"
        elif "Pipfile" in names:
            meta["python_backend"] = "pipenv"
        else:
            meta["python_backend"] = "pip"

        req_content = _safe_read(target_dir / "requirements.txt") + "\n" + _safe_read(target_dir / "pyproject.toml")
        native_pkgs = {"psycopg2", "pillow", "cryptography", "pandas", "numpy", "cffi", "lxml", "scipy", "mysqlclient", "xgboost", "scikit-learn", "opencv-python", "opencv-python-headless", "torch", "lightgbm"}
        meta["python_needs_build_tools"] = any(re.search(rf"\b{pkg}\b", req_content, re.I) for pkg in native_pkgs)

        for c in [
            "server.py", "app.py", "main.py", "manage.py", "run.py", "wsgi.py", "asgi.py",
            "app/main.py", "src/main.py", "api/main.py",
            "app/app.py", "src/app.py", "api/app.py",
            "app/server.py", "src/server.py", "api/server.py",
            "app/run.py", "src/run.py"
        ]:
            if c in rel:
                meta["entry"] = c
                break

        if not meta["entry"]:
            for f in files:
                if f.suffix == ".py":
                    f_rel = f.relative_to(target_dir).as_posix()
                    txt = _safe_read(f)
                    if re.search(r"=\s*(?:fastapi\.)?FastAPI\(", txt) or re.search(r"=\s*(?:flask\.)?Flask\(", txt):
                        meta["entry"] = f_rel
                        break

        if not meta["entry"]:
            root_py = [f.name for f in files if f.parent == target_dir and f.suffix == ".py"]
            if root_py:
                meta["entry"] = root_py[0]
            else:
                any_py = [f.relative_to(target_dir).as_posix() for f in files if f.suffix == ".py"]
                meta["entry"] = any_py[0] if any_py else "app.py"

        if "manage.py" in names:
            meta["framework"] = "django"
            meta["django_wsgi"] = _detect_django_wsgi(files, target_dir)
        else:
            meta["framework"] = _detect_python_framework(meta["entry"], files, target_dir)
            if meta["framework"] == "flask":
                meta["flask_app"] = _detect_flask_app(meta["entry"], files, target_dir)

    # 5. Go
    elif "go.mod" in root_names:
        go_ver = "1.23"
        go_text = _safe_read(target_dir / "go.mod")
        m_go = re.search(r"^go\s+(\d+\.\d+)", go_text, re.M)
        if m_go:
            go_ver = m_go.group(1)
        needs_cgo = bool(re.search(r"(go-sqlite3|mattn/go-sqlite3)", go_text, re.I))
        if not needs_cgo:
            for gf in files:
                if gf.suffix == ".go" and 'import "C"' in _safe_read(gf):
                    needs_cgo = True
                    break
        meta.update(stack="go", port=_detect_port(files, 8080), entry=_detect_go_entry(rel),
                    go_version=go_ver, go_cgo=needs_cgo)

    # 6. Rust
    elif "Cargo.toml" in root_names:
        meta.update(stack="rust", port=_detect_port(files, 8080), entry=_detect_rust_bin())

    # 7. Java (Maven / Gradle / Raw javac)
    elif ("pom.xml" in root_names or "build.gradle" in root_names or "build.gradle.kts" in root_names
          or any(f.suffix == ".java" for f in files)):
        j_ver = "21"
        is_spring = False
        if "pom.xml" in names:
            tool = "maven"
            entry = "pom.xml"
        elif "build.gradle" in names or "build.gradle.kts" in names:
            tool = "gradle"
            entry = "build.gradle" if "build.gradle" in names else "build.gradle.kts"
        else:
            tool = "javac"
            entry = "src"

        for f in files:
            if f.name == "pom.xml":
                txt = _safe_read(f)
                m = re.search(r"<(?:java\.version|maven\.compiler\.target|release)>(\d+)</", txt, re.I)
                if m and m.group(1) in {"8", "11", "17", "21"}:
                    j_ver = m.group(1)
                if "spring-boot" in txt:
                    is_spring = True
            elif f.name in {"build.gradle", "build.gradle.kts"}:
                txt = _safe_read(f)
                m = re.search(r"(?:sourceCompatibility|jvmTarget)\s*=\s*['\"]?(\d+)['\"]?", txt, re.I)
                if m and m.group(1) in {"8", "11", "17", "21"}:
                    j_ver = m.group(1)
                if "org.springframework.boot" in txt:
                    is_spring = True
        meta.update(stack="java", java_tool=tool, java_version=j_ver, is_spring=is_spring,
                    port=_detect_port(files, 8080), entry=entry)

    # 8. PHP
    elif "composer.json" in root_names or any(f.suffix == ".php" for f in files if f.parent == target_dir or f.parent.name in {"src", "public", "app"}):
        meta.update(stack="php", port=_detect_port(files, 80), entry="index.php",
                    has_composer="composer.json" in root_names)

    # 9. Ruby
    elif "Gemfile" in root_names:
        meta.update(stack="ruby", port=_detect_port(files, 3000), entry="config.ru" if "config.ru" in names else "app.rb")

    # 10. Static Site
    elif any(f.name == "index.html" for f in files):
        meta.update(stack="static", port=80, entry="index.html")

    # Database detection
    if no_db:
        meta["databases"] = []
    elif db_override:
        meta["databases"] = [d.strip().lower() for d in db_override.split(",") if d.strip()]
    else:
        meta["databases"], meta["db_name"], meta["db_init_sql"], meta["sqlite_file"] = _detect_databases_accurately(files, names)

    return meta


def inspect_project(db_override: str = None, no_db: bool = False) -> dict:
    root_manifests = {
        "package.json", "requirements.txt", "pyproject.toml", "Pipfile", "setup.py",
        "go.mod", "pom.xml", "build.gradle", "build.gradle.kts", "Cargo.toml",
        "Gemfile", "composer.json", "index.html", "server.js", "app.js", "server.py", "app.py"
    }
    has_root_manifest = any((ROOT / m).exists() for m in root_manifests) or any(
        f.suffix in {".csproj", ".sln", ".fsproj"} for f in ROOT.iterdir() if f.is_file()
    )

    if has_root_manifest:
        return _inspect_single_project(ROOT, db_override=db_override, no_db=no_db)

    # ROOT has NO direct manifest. Check immediate subdirectories for Monorepo or Subprojects
    subdirs = [d for d in ROOT.iterdir() if d.is_dir() and d.name not in SKIP_DIRS and not d.name.startswith(".")]

    backend_names = {"backend", "server", "api", "custom-backend", "srv", "app"}
    frontend_names = {"frontend", "client", "web", "ui", "site"}

    backend_dir = None
    frontend_dir = None

    for d in subdirs:
        d_name = d.name.lower()
        if d_name in backend_names:
            backend_dir = d
        elif d_name in frontend_names:
            frontend_dir = d

    if not backend_dir:
        for d in subdirs:
            if (d / "package.json").exists():
                pkg_txt = _safe_read(d / "package.json")
                if any(k in pkg_txt for k in ["express", "fastify", "koa", "nest", "mongoose", "pg", "typeorm"]):
                    backend_dir = d
                    break
            elif (d / "requirements.txt").exists() or (d / "manage.py").exists():
                backend_dir = d
                break

    if not frontend_dir:
        for d in subdirs:
            if d == backend_dir:
                continue
            if any((d / f).exists() for f in ["vite.config.ts", "vite.config.js", "next.config.js", "index.html"]):
                frontend_dir = d
                break

    if backend_dir and frontend_dir:
        b_meta = _inspect_single_project(backend_dir, db_override=db_override, no_db=no_db)
        f_meta = _inspect_single_project(frontend_dir, no_db=True)
        meta = _blank_meta()
        meta["stack"] = "fullstack_monorepo"
        meta["backend_dir"] = backend_dir
        meta["frontend_dir"] = frontend_dir
        meta["backend_meta"] = b_meta
        meta["frontend_meta"] = f_meta
        meta["databases"] = b_meta.get("databases", [])
        meta["db_name"] = b_meta.get("db_name", PROJECT_NAME)
        meta["db_init_sql"] = b_meta.get("db_init_sql")
        meta["sqlite_file"] = b_meta.get("sqlite_file")
        meta["port"] = 80
        meta["backend_port"] = b_meta.get("port", 5000) or 5000
        return meta

    if backend_dir and not frontend_dir:
        b_meta = _inspect_single_project(backend_dir, db_override=db_override, no_db=no_db)
        b_meta["target_subdir"] = backend_dir.name
        return b_meta

    if frontend_dir and not backend_dir:
        f_meta = _inspect_single_project(frontend_dir, db_override=db_override, no_db=no_db)
        f_meta["target_subdir"] = frontend_dir.name
        return f_meta

    valid_subdirs = [
        d for d in subdirs if (d / "package.json").exists() or (d / "requirements.txt").exists() or (d / "index.html").exists()
    ]
    if valid_subdirs:
        chosen = valid_subdirs[0]
        c_meta = _inspect_single_project(chosen, db_override=db_override, no_db=no_db)
        c_meta["target_subdir"] = chosen.name
        return c_meta

    return _inspect_single_project(ROOT, db_override=db_override, no_db=no_db)


def _blank_meta():
    return {
        "stack": "static", "port": 80, "entry": None, "target_dir": None,
        "pkg_manager": "npm", "lockfile": None, "has_build": False,
        "node_version": "22", "next_standalone": False, "node_needs_dev_runtime": False,
        "python_backend": "pip", "python_version": "3.11",
        "python_needs_build_tools": False, "framework": "generic",
        "django_wsgi": None, "flask_app": None,
        "java_tool": "maven", "java_version": "21", "is_spring": False,
        "go_version": "1.23", "go_cgo": False,
        "dotnet_version": "9.0", "dotnet_dll": "app.dll",
        "dotnet_is_legacy": False, "dotnet_is_console": False,
        "databases": [], "db_name": "app_db", "db_init_sql": None, "sqlite_file": None
    }


def _detect_node_version(files, pkg: dict) -> str:
    for f in files:
        if f.name in {".nvmrc", ".node-version"}:
            txt = _safe_read(f).strip().lstrip("v")
            m = re.match(r"^(\d+)", txt)
            if m and int(m.group(1)) >= 18:
                return m.group(1)
    engines = pkg.get("engines", {})
    if "node" in engines:
        m = re.search(r"(\d+)", engines["node"])
        if m and int(m.group(1)) >= 18:
            return m.group(1)
    return "22"


def _detect_python_version(files, target_dir: Path = None) -> str:
    for f in files:
        if f.name in {".python-version", "runtime.txt"}:
            txt = _safe_read(f).strip()
            m = re.search(r"3\.(\d+)", txt)
            if m:
                return f"3.{m.group(1)}"
        elif f.name == "pyproject.toml":
            txt = _safe_read(f)
            m = re.search(r'requires-python\s*=\s*["\'](?:>=?~?)?\s*3\.(\d+)', txt)
            if m:
                return f"3.{m.group(1)}"
            m = re.search(r'python\s*=\s*["\'](?:[~^>=<]*)\s*3\.(\d+)', txt)
            if m:
                return f"3.{m.group(1)}"
        elif f.name == "Pipfile":
            txt = _safe_read(f)
            m = re.search(r'python_version\s*=\s*["\']3\.(\d+)["\']', txt)
            if m:
                return f"3.{m.group(1)}"

    req_file = (target_dir / "requirements.txt") if target_dir else (ROOT / "requirements.txt")
    if not req_file.exists():
        req_file = next((f for f in files if f.name == "requirements.txt"), None)
    if req_file and req_file.exists():
        req_text = _safe_read(req_file)

        # Check explicit python_version marker
        m = re.search(r'python_version\s*(?:==|<=|<|>=)\s*["\']3\.(\d+)["\']', req_text)
        if m:
            return f"3.{m.group(1)}"

        # Django version compatibility detection
        dm = re.search(r'^\s*django\s*([=><~^!]+)\s*([0-9]+)(?:\.([0-9]+))?', req_text, re.M | re.I)
        if dm:
            major = int(dm.group(2))
            minor = int(dm.group(3) or 0)
            if major < 3 or (major == 3 and minor <= 1):
                return "3.8"
            elif major == 3 and minor == 2:
                return "3.9"
            elif major == 4 and minor <= 1:
                return "3.10"
            elif major == 4 and minor == 2:
                return "3.11"
            elif major >= 5:
                return "3.12"

        # Legacy packages with strict Python version constraints
        if re.search(r'^\s*protobuf\s*==\s*3\.', req_text, re.M | re.I):
            return "3.8"
        if re.search(r'^\s*tensorflow\s*==\s*1\.', req_text, re.M | re.I):
            return "3.7"
        if re.search(r'^\s*tensorflow\s*==\s*2\.[0-5]', req_text, re.M | re.I):
            return "3.8"

    return "3.11"


def _detect_django_wsgi(files, target_dir: Path = None) -> str:
    t_dir = target_dir or ROOT
    for f in files:
        if f.name == "wsgi.py":
            try:
                rel_parts = f.relative_to(t_dir).parts
                if len(rel_parts) >= 2:
                    return f"{'.'.join(rel_parts[:-1])}.wsgi:application"
            except Exception:
                pass
    manage_f = (t_dir / "manage.py") if (t_dir / "manage.py").exists() else next((f for f in files if f.name == "manage.py"), None)
    if manage_f and manage_f.exists():
        txt = _safe_read(manage_f)
        m = re.search(r"['\"]([a-zA-Z0-9_]+)\.settings['\"]", txt)
        if m:
            return f"{m.group(1)}.wsgi:application"
    return f"{PROJECT_NAME}.wsgi:application"


